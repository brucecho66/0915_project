-- 9. Row Level Security (RLS) 설정
-- Express 백엔드 서버(service_role key)를 통해 중앙 제어하므로 RLS는 기본 비활성화하거나 서비스 롤 완전 허용 설정
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.comments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.post_reactions ENABLE ROW LEVEL SECURITY;

-- 백엔드 서비스 키 및 anon 접근 정책 (모든 쿼리 허용 - 세부 인증/권한은 Express 백엔드에서 JWT로 검증)
CREATE POLICY "Allow all access to service and anon" ON public.users FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all access to service and anon" ON public.posts FOR ALL USING (true) WITH CHECK (true);
CREATE POLICY "Allow all access to service and anon" ON public.comments FOR ALL USING (true) WITH CHECK (true);
