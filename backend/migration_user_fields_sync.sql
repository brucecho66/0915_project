ALTER TABLE public.users ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW());

-- 2. public.profiles 테이블 확인 및 컬럼 보강
CREATE TABLE IF NOT EXISTS public.profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  admin_id BIGINT REFERENCES public.admins(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  username TEXT NOT NULL,
  bio TEXT DEFAULT '',
  avatar_url TEXT DEFAULT '',
  role TEXT DEFAULT 'user' CHECK(role IN ('admin', 'user')),
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()),
  updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()),
  CONSTRAINT unique_profile_email UNIQUE (email)
);

-- 3. 기존 users 테이블의 bio, avatar_url 데이터를 profiles 테이블과 동기화
INSERT INTO public.profiles (user_id, email, username, bio, avatar_url, role, created_at)
SELECT id, email, username, COALESCE(bio, ''), COALESCE(avatar_url, ''), role, created_at
FROM public.users
ON CONFLICT (email) DO UPDATE
SET user_id = EXCLUDED.user_id,
    username = EXCLUDED.username,
    bio = EXCLUDED.bio,
    avatar_url = EXCLUDED.avatar_url,
    updated_at = NOW();

-- 4. 인덱스 생성
CREATE INDEX IF NOT EXISTS idx_users_avatar ON public.users(avatar_url);
CREATE INDEX IF NOT EXISTS idx_profiles_avatar ON public.profiles(avatar_url);
