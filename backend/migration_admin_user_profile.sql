-- 1. 관리자(admins) 테이블 생성
-- 관리자 계정 정보만 독립적으로 보관 및 관리
CREATE TABLE IF NOT EXISTS public.admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  username TEXT NOT NULL,
  password TEXT NOT NULL,
  role TEXT DEFAULT 'admin',
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()),
  updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW())
);

-- 2. 일반 사용자(users) 테이블 보강
-- 일반 회원 계정 정보(인증 및 자격증명)를 독립적으로 관리
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  username TEXT NOT NULL,
  password TEXT NOT NULL,
  role TEXT DEFAULT 'user',
  bio TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()),
  updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW())
);

-- 3. 프로필(profiles) 테이블 생성
-- 유저 또는 관리자의 자기소개, 아바타 등 프로필 데이터를 별도 분리하여 관리
-- (유저만 있거나 프로필만 있는 경우 모두 유연하게 수용할 수 있도록 외래키 NULL 허용)
CREATE TABLE IF NOT EXISTS public.profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES public.users(id) ON DELETE CASCADE,
  admin_id BIGINT REFERENCES public.admins(id) ON DELETE CASCADE,
  email TEXT NOT NULL,
  username TEXT NOT NULL,
  bio TEXT DEFAULT '',
  avatar_url TEXT DEFAULT '',
  role TEXT DEFAULT 'user' CHECK(role IN ('admin', 'user')),
  created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()),
  updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW()),
  CONSTRAINT unique_profile_email UNIQUE (email)
);

-- 4. 인덱스 생성
CREATE INDEX IF NOT EXISTS idx_admins_email ON public.admins(email);
CREATE INDEX IF NOT EXISTS idx_users_email ON public.users(email);
CREATE INDEX IF NOT EXISTS idx_profiles_email ON public.profiles(email);
CREATE INDEX IF NOT EXISTS idx_profiles_user_id ON public.profiles(user_id);
CREATE INDEX IF NOT EXISTS idx_profiles_admin_id ON public.profiles(admin_id);

-- 5. 데이터 마이그레이션: 기존 users 테이블의 관리자 데이터를 admins 테이블로 분리 복사
INSERT INTO public.admins (email, username, password, role, created_at)
SELECT email, username, password, 'admin', created_at
FROM public.users
WHERE role = 'admin'
ON CONFLICT (email) DO UPDATE
SET username = EXCLUDED.username,
    password = EXCLUDED.password,
    role = 'admin',
    updated_at = NOW();

